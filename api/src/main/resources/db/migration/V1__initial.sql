CREATE TABLE app_user (email varchar(254) PRIMARY KEY, password_hash varchar(100) NOT NULL);
CREATE TABLE records (
 id uuid PRIMARY KEY, owner varchar(254) NOT NULL REFERENCES app_user(email),
 module varchar(40) NOT NULL, data jsonb NOT NULL, version bigint NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX records_owner_module ON records(owner,module);
CREATE TABLE record_history (id bigserial PRIMARY KEY, record_id uuid NOT NULL, owner varchar(254) NOT NULL, data jsonb NOT NULL, recorded_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE preferences (owner varchar(254) PRIMARY KEY REFERENCES app_user(email), data jsonb NOT NULL);
CREATE TABLE external_cache (kind varchar(30) PRIMARY KEY, data jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY, SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL, LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL, PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BYTEA NOT NULL,
 PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
